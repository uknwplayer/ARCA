import {readFile,writeFile,mkdir} from "node:fs/promises";
import {dirname} from "node:path";
import {CrossPeerRequestOwnershipStore} from "../../src/machine-bridge/cross-peer-request-ownership.mjs";
import {MeshIdentityTrustStore} from "../../src/machine-bridge/mesh-identity.mjs";
import {observeRemoteRequestEvidence,verifyRemoteRequestEvidenceStatement} from "../../src/machine-bridge/remote-request-evidence.mjs";

const [requestId] = process.argv.slice(2);
if(!/^[A-Za-z0-9._-]{1,120}$/.test(requestId??"")) throw new Error("ARCA_FEDERATION_INVALID_REQUEST_ID");
const token=process.env.ARCA_FEDERATION_B_TRANSPORT_TOKEN;
if(!token) throw new Error("ARCA_FEDERATION_TRANSPORT_UNAVAILABLE");
const ownershipStore=await new CrossPeerRequestOwnershipStore({root:".arca/federation/ownership"}).init();
const ownership=await ownershipStore.status(requestId);
if(ownership.state==="unbound") throw new Error("ARCA_FEDERATION_OWNERSHIP_UNBOUND");
if(ownership.selectedNodeId!=="arca-federation-operator-b") throw new Error("ARCA_FEDERATION_SELECTED_NODE_MISMATCH");
const trustIdentity=JSON.parse(await readFile("federation/trust/operator-b.mesh-identity.json","utf8"));
const trustStore=new MeshIdentityTrustStore();
trustStore.trust(trustIdentity);
const targetRepo=process.env.ARCA_FEDERATION_B_REPOSITORY;
const targetRef=process.env.ARCA_FEDERATION_B_REF??"main";
if(!/^[A-Za-z0-9_.-]+\/[A-Za-z0-9_.-]+$/.test(targetRepo??"")) throw new Error("ARCA_FEDERATION_TARGET_REPOSITORY_REQUIRED");
const endpoint="https://api.github.com/repos/"+targetRepo+"/contents/federation/outbox/"+encodeURIComponent(requestId)+".json?ref="+encodeURIComponent(targetRef);
const response=await fetch(endpoint,{headers:{Accept:"application/vnd.github.raw+json",Authorization:"Bearer "+token,"X-GitHub-Api-Version":"2022-11-28","User-Agent":"arca-machine-bridge"}});
if(response.status===404) throw new Error("ARCA_FEDERATION_REMOTE_EVIDENCE_UNSEEN");
if(!response.ok) throw new Error("ARCA_FEDERATION_REMOTE_EVIDENCE_FETCH_FAILED_"+response.status);
const remote=JSON.parse(await response.text());
const accepted=remote?.canonicalEvidence?.accepted;
const completed=remote?.canonicalEvidence?.completed;
if(!accepted||!completed) throw new Error("ARCA_FEDERATION_REMOTE_EVIDENCE_INCOMPLETE");
const common={trustStore,expectedNodeId:ownership.selectedNodeId,expectedRequestId:ownership.requestId,expectedJobId:ownership.jobId,expectedPayloadHash:ownership.payloadHash,expectedOwnerBindingHash:ownership.bindingHash};
const a=verifyRemoteRequestEvidenceStatement(accepted,{...common,expectedStage:"accepted"});
const c=verifyRemoteRequestEvidenceStatement(completed,{...common,expectedStage:"completed"});
if(c.evidence.acceptedStatementHash!==accepted.statementHash) throw new Error("ARCA_FEDERATION_ACCEPTANCE_BINDING_MISMATCH");
await observeRemoteRequestEvidence(accepted,{trustStore,ownershipStore});
await observeRemoteRequestEvidence(completed,{trustStore,ownershipStore});
const after=await ownershipStore.status(requestId);
if(after.state!=="completed"||after.resultHash!==c.evidence.resultHash) throw new Error("ARCA_FEDERATION_RECONCILIATION_FAILED");
const proof={format:"arca-federation-reconciliation-proof-v1",version:1,requestId,nodeId:ownership.selectedNodeId,acceptedStatementHash:accepted.statementHash,completedStatementHash:completed.statementHash,resultHash:after.resultHash,reconciledAt:new Date().toISOString()};
const path=".arca/federation/reconciliation/"+requestId+".json";
await mkdir(dirname(path),{recursive:true});
await writeFile(path,JSON.stringify(proof,null,2)+"\n","utf8");
console.log("reconciled_request_id="+requestId);
console.log("result_hash="+after.resultHash);
